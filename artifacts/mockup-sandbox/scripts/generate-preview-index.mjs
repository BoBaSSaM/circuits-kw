import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import glob from "fast-glob";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = path.join(packageRoot, "src/.generated/mockup-components.ts");

export async function generatePreviewIndex() {
  const files = await glob("src/components/mockups/**/*.tsx", {
    cwd: packageRoot,
    ignore: ["**/_*/**", "**/_*.tsx"],
    onlyFiles: true,
  });
  const entries = files
    .sort()
    .map((file) => {
      const globKey = `./${file.slice("src/".length)}`;
      const importPath = path.posix.relative("src/.generated", file);
      return `  ${JSON.stringify(globKey)}: () => import(${JSON.stringify(importPath)})`;
    })
    .join(",\n");
  const source = [
    "// This file is generated by scripts/generate-preview-index.mjs.",
    "type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;",
    "export const modules: ModuleMap = {",
    entries,
    "};",
    "",
  ].join("\n");

  await mkdir(path.dirname(generatedPath), { recursive: true });
  let previous = "";
  try {
    previous = await readFile(generatedPath, "utf8");
  } catch {
    // Generate the file on first use.
  }
  if (previous !== source) await writeFile(generatedPath, source);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generatePreviewIndex();
}
